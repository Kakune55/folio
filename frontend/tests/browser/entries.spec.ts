import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
async function login(page: Page) {
  await page.goto('/')
  await page.getByLabel('密码', { exact: true }).fill('folio-browser-test-password-2026')
  await page.getByRole('button', { name: '进入工作区' }).click()
  await expect(page.getByRole('button', { name: '退出登录' })).toBeVisible()
}
async function create(page: Page, kind: '笔记' | '文件夹', name: string) {
  await page.getByRole('button', { name: `新建${kind}`, exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill(name)
  await dialog.getByRole('button', { name: '创建', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}
async function menu(page: Page, name: string, action: string) {
  await page.getByRole('button', { name: `文件操作 ${name}`, exact: true }).click()
  await page.getByRole('menuitem', { name: action, exact: true }).click()
}

test('行内重命名与移动目录保留正文，后续保存使用新路径', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message))
  await login(page)
  const folder = `路径-${Date.now()}`
  await create(page, '文件夹', folder)
  await create(page, '笔记', '原名.md')
  await page.getByRole('button', { name: folder, exact: true }).click()
  const rich = page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true })
  await rich.fill('重命名前未保存的正文')
  await menu(page, '原名.md', '重命名')
  const rename = page.getByRole('textbox', { name: '重命名 原名.md', exact: true })
  await rename.fill('新名.md'); await rename.press('Enter')
  await expect(page.getByRole('tab', { name: '新名.md', exact: true })).toBeVisible()
  await expect(rich).toContainText('重命名前未保存的正文')
  await expect(page.locator('.save-status')).toHaveText('已保存')
  await menu(page, folder, '重命名')
  const renameFolder = page.getByRole('textbox', { name: `重命名 ${folder}`, exact: true })
  await renameFolder.fill(`${folder}-已移动`); await renameFolder.press('Enter')
  await expect(page.getByRole('button', { name: `${folder}-已移动`, exact: true })).toBeVisible()
  const target = `${folder}-目标`
  const principal = await (await page.request.get('/api/v1/auth/me')).json()
  expect((await page.request.post('/api/v1/directories', { headers: { 'X-CSRF-Token': principal.csrfToken }, data: { path: target } })).status()).toBe(201)
  await menu(page, `${folder}-已移动`, '移动到…')
  const dialog = page.getByRole('dialog', { name: '移动到', exact: true })
  await dialog.getByRole('button', { name: `进入目录 ${target}`, exact: true }).click()
  await dialog.getByRole('button', { name: '移动到此', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await rich.fill('移动之后继续保存')
  await expect(page.locator('.save-status')).toHaveText('已保存')
  const result = await page.request.get(`/api/v1/files/content?path=${encodeURIComponent(`${target}/${folder}-已移动/新名.md`)}`)
  expect(result.status()).toBe(200)
  expect((await result.json()).content).toContain('移动之后继续保存')
  expect((await page.request.get(`/api/v1/files/content?path=${encodeURIComponent(`${folder}/原名.md`)}`)).status()).toBe(404)
  expect(errors).toEqual([])
})

test('文件夹移入回收站后恢复，碰撞保留两份内容', async ({ page }) => {
  await login(page)
  const folder = `回收-${Date.now()}`
  await create(page, '文件夹', folder)
  await create(page, '笔记', '恢复.md')
  await page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true }).fill('删除前的完整内容')
  await expect(page.locator('.save-status')).toHaveText('已保存')
  await menu(page, folder, '移到回收站')
  const confirmation = page.getByRole('dialog')
  await confirmation.getByRole('button', { name: '移到回收站', exact: true }).click()
  await expect(confirmation).not.toBeVisible()
  await expect(page.getByRole('tab', { name: '恢复.md', exact: true })).not.toBeVisible()
  await page.getByRole('button', { name: '打开回收站' }).click()
  const trash = page.getByRole('dialog')
  await expect(trash.getByText(folder, { exact: true })).toBeVisible()
  const principal = await (await page.request.get('/api/v1/auth/me')).json()
  expect((await page.request.post('/api/v1/directories', { headers: { 'X-CSRF-Token': principal.csrfToken }, data: { path: folder } })).status()).toBe(201)
  await trash.getByRole('button', { name: '恢复', exact: true }).click()
  await expect(trash.getByText('同名文件或目录已存在', { exact: true })).toBeVisible()
  const placeholder = await (await page.request.get(`/api/v1/entries/revision?path=${encodeURIComponent(folder)}`)).json()
  expect((await page.request.delete(`/api/v1/entries?path=${encodeURIComponent(folder)}`, { headers: { 'X-CSRF-Token': principal.csrfToken, 'If-Match': `"${placeholder.revision}"` } })).status()).toBe(200)
  await trash.getByRole('button', { name: '刷新回收站', exact: true }).click()
  await trash.getByLabel('回收记录排序').selectOption('oldest')
  await trash.getByRole('button', { name: '恢复', exact: true }).first().click()
  await expect(trash.getByText(`已恢复 ${folder}`, { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/trash-restored.png' })
  await trash.getByRole('button', { name: '关闭回收站' }).click()
  await page.getByRole('button', { name: folder, exact: true }).click()
  await page.getByRole('button', { name: '恢复.md', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Markdown 编辑器', exact: true })).toContainText('删除前的完整内容')
})

test('回收站按已加载范围搜索、排序和全选，批量恢复', async ({ page }) => {
  await login(page)
  let records = Array.from({ length: 63 }, (_, i) => ({ id: `item-${i}`, path: `归档/笔记-${String(i).padStart(2, '0')}.md`, kind: 'file', revision: 'v1', deletedAt: new Date(2026, 10, 17, 0, i).toISOString(), state: 'ready' }))
  const restored: string[] = []
  await page.route('**/api/v1/trash?*', async (route) => {
    const offset = Number(new URL(route.request().url()).searchParams.get('offset'))
    await route.fulfill({ json: { entries: records.slice(offset, offset + 50), total: records.length, offset, limit: 50 } })
  })
  await page.route('**/api/v1/trash/*/restore', async (route) => {
    const id = route.request().url().split('/').at(-2)!
    restored.push(id); records = records.filter((record) => record.id !== id)
    await route.fulfill({ json: { path: '归档/已恢复.md' } })
  })
  await page.getByRole('button', { name: '打开回收站' }).click()
  const trash = page.getByRole('dialog', { name: '回收站', exact: true })
  await expect(trash.getByRole('contentinfo')).toContainText('共 63 项 · 已加载 50 项')
  await page.screenshot({ path: 'test-results/trash-list-desktop.png' })
  await trash.getByLabel('搜索已加载的回收记录').fill('笔记-6')
  await expect(trash.getByText('已加载记录中没有匹配项')).toBeVisible()
  await trash.getByRole('button', { name: '加载更多', exact: true }).click()
  await expect(trash.getByRole('row')).toHaveCount(4)
  await trash.getByLabel('回收记录排序').selectOption('name')
  await expect(trash.getByRole('row').nth(1)).toContainText('笔记-60.md')
  await trash.getByLabel('全选当前列表', { exact: true }).check()
  await expect(trash.getByText('已选择 3 项')).toBeVisible()
  await trash.getByRole('button', { name: '恢复所选', exact: true }).click()
  await expect(trash.getByText('已恢复 3 项。', { exact: true })).toBeVisible()
  expect(restored).toEqual(['item-60', 'item-61', 'item-62'])
})

test('回收站批量删除需确认，失败停止且刷新核对后才能继续', async ({ page }) => {
  await login(page)
  let records = ['a', 'b', 'c', 'damaged', 'incomplete'].map((id) => ({ id, path: `目录/${id}.md`, kind: 'file', revision: 'v1', deletedAt: '2026-11-17T00:00:00Z', state: id === 'damaged' ? 'damaged' : id === 'incomplete' ? 'pending' : 'ready' }))
  const deleted: string[] = []
  await page.route('**/api/v1/trash?*', (route) => route.fulfill({ json: { entries: records, total: records.length, offset: 0, limit: 50 } }))
  await page.route('**/api/v1/trash/*', async (route) => {
    const id = route.request().url().split('/').at(-1)!
    deleted.push(id)
    if (id === 'b') { await route.abort(); return }
    records = records.filter((record) => record.id !== id)
    await route.fulfill({ json: {} })
  })
  await page.getByRole('button', { name: '打开回收站' }).click()
  const trash = page.getByRole('dialog', { name: '回收站', exact: true })
  const damaged = trash.getByRole('row').filter({ hasText: 'damaged.md' })
  await expect(damaged.getByRole('button', { name: '尝试恢复' })).toBeDisabled()
  await expect(damaged.getByRole('button', { name: '永久删除', exact: true })).toBeDisabled()
  const incomplete = trash.getByRole('row').filter({ hasText: 'incomplete.md' })
  await expect(incomplete.getByRole('button', { name: '尝试恢复' })).toBeEnabled()
  await expect(incomplete.getByRole('button', { name: '永久删除', exact: true })).toBeDisabled()
  await trash.getByLabel('全选当前列表', { exact: true }).check()
  await expect(trash.getByRole('button', { name: '删除所选', exact: true })).toBeDisabled()
  await trash.getByLabel('全选当前列表', { exact: true }).uncheck()
  for (const id of ['a', 'b', 'c']) await trash.getByLabel(`选择 目录/${id}.md`, { exact: true }).check()
  await trash.getByRole('button', { name: '删除所选', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: '永久删除', exact: true })
  await expect(confirm.getByRole('listitem')).toHaveCount(3)
  await confirm.getByRole('button', { name: '取消', exact: true }).click()
  expect(deleted).toEqual([])
  await trash.getByRole('button', { name: '删除所选', exact: true }).click()
  await confirm.getByRole('button', { name: '确认永久删除', exact: true }).click()
  await expect(trash.getByText(/已完成 1 项，其余操作已停止/)).toBeVisible()
  expect(deleted).toEqual(['a', 'b'])
  await expect(trash.getByLabel('选择 目录/c.md', { exact: true })).toBeDisabled()
  await trash.getByRole('button', { name: '刷新回收站', exact: true }).click()
  await expect(trash.getByLabel('选择 目录/c.md', { exact: true })).toBeEnabled()
  await expect(trash.getByRole('button', { name: '删除所选', exact: true })).toBeDisabled()
})

test('手机回收站长路径不撑宽窗口，明暗主题均可操作', async ({ page }) => {
  await login(page)
  await page.setViewportSize({ width: 390, height: 740 })
  await page.getByRole('button', { name: '关闭文件列表', exact: true }).click()
  const path = `很长的原始目录/${'超长文件名'.repeat(15)}.md`
  await page.route('**/api/v1/trash?*', (route) => route.fulfill({ json: { entries: [{ id: 'long', path, kind: 'file', revision: 'v1', deletedAt: '2026-11-17T00:00:00Z', state: 'ready' }], total: 1, offset: 0, limit: 50 } }))
  await page.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '打开回收站' }).click()
  const trash = page.getByRole('dialog', { name: '回收站', exact: true })
  await expect(trash.getByLabel(`选择 ${path}`, { exact: true })).toBeVisible()
  for (const theme of ['light', 'dark']) {
    await page.evaluate((value) => { document.documentElement.dataset.theme = value }, theme)
    expect(await trash.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await expect(trash.getByRole('button', { name: '恢复', exact: true })).toBeVisible()
    await page.screenshot({ path: `test-results/trash-mobile-${theme}.png` })
  }
  await trash.getByRole('button', { name: '关闭回收站' }).click()
  await expect(trash).not.toBeVisible()
})
