test('触屏通过文件选择器上传图片与 PDF，预览和下载保持原始字节', async ({ page }) => {
  await login(page)
  const panel = await drawer(page), folder = `手机附件-${Date.now()}`
  await create(page, '文件夹', folder)
  const directory = panel.getByRole('button', { name: folder, exact: true })
  if (await directory.getAttribute('aria-expanded') !== 'true') await directory.tap()
  const chooser = page.waitForEvent('filechooser')
  await panel.getByRole('button', { name: `上传到「${folder}」`, exact: true }).tap()
  await (await chooser).setFiles([resolve('tests/fixtures/preview.png'), resolve('tests/fixtures/preview.pdf')])
  await expect(panel.getByText('已上传 2 个文件。', { exact: true })).toBeVisible()
  await expect(page.locator('input[aria-label="拍照上传文件"]')).toHaveAttribute('capture', 'environment')
  await page.route('**/api/v1/uploads?**', (route) => route.abort())
  const camera = page.waitForEvent('filechooser')
  await panel.getByRole('button', { name: '拍照上传', exact: true }).tap()
  await (await camera).setFiles({ name: '手机拍照.png', mimeType: 'image/png', buffer: await readFile(resolve('tests/fixtures/preview.png')) })
  const original = page.waitForEvent('download')
  await panel.getByRole('button', { name: /^下载待上传原件 photo-.*手机拍照\.png$/ }).tap()
  expect(await readFile((await (await original).path())!)).toEqual(await readFile(resolve('tests/fixtures/preview.png')))
  await page.unroute('**/api/v1/uploads?**')
  await panel.getByRole('button', { name: '重试到当前目录', exact: true }).tap()
  await expect(panel.getByText('已上传 1 个文件。', { exact: true })).toBeVisible()
  await panel.getByRole('button', { name: 'preview.png', exact: true }).tap()
  await expect(panel).not.toBeVisible()
  await expect(page.getByRole('img', { name: 'preview.png', exact: true })).toBeVisible()
  await drawer(page)
  await panel.getByRole('button', { name: 'preview.pdf', exact: true }).tap()
  await expect(page.getByText('正在渲染 PDF…', { exact: true })).not.toBeVisible()
  await expect(page.locator('.pdf-toolbar span')).toHaveText('1 / 1')
  await expect(page.getByRole('img', { name: 'PDF 第 1 页', exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '下载原文件', exact: true }).tap()
  expect(await readFile((await (await download).path())!)).toEqual(await readFile(resolve('tests/fixtures/preview.pdf')))
  await page.screenshot({ path: 'test-results/mobile-pdf-light.png' })
})

test('触屏保存失败后刷新，恢复入口和手动保存均可操作', async ({ page }) => {
  await login(page)
  await drawer(page)
  const name = `手机恢复-${Date.now()}.json`
  await create(page, '笔记', name)
  await page.route('**/api/v1/files/content?**', (route) => route.request().method() === 'PUT' ? route.abort() : route.continue())
  const editor = page.getByRole('textbox', { name: '源码编辑器' })
  await editor.tap(); await page.keyboard.insertText('手机未保存的最后正文')
  await expect(page.locator('.save-status')).toContainText('保存失败')
  await expect.poll(async () => page.evaluate(async (path) => new Promise<string | undefined>((resolve) => {
    const request = indexedDB.open('folio-recovery', 1)
    request.onsuccess = () => { const db = request.result, transaction = db.transaction('drafts', 'readonly'), query = transaction.objectStore('drafts').getAll(); transaction.oncomplete = () => { db.close(); resolve(query.result.find((draft: { path: string }) => draft.path === path)?.source) } }
  }), name)).toBe('手机未保存的最后正文')
  await page.reload()
  // 自动恢复的是磁盘标签；先关闭，保留恢复稿显式打开的保护。
  await expect(page.getByRole('tab', { name, exact: true })).toBeVisible()
  await page.getByRole('tab', { name, exact: true }).locator('.tab-close-target').tap()
  await page.getByRole('button', { name: '查看浏览器恢复稿' }).tap()
  const dialog = page.getByRole('dialog', { name: '浏览器恢复稿', exact: true })
  await dialog.getByRole('button').filter({ hasText: name }).tap()
  await expect(dialog.getByLabel('浏览器草稿正文')).toHaveValue('手机未保存的最后正文')
  await dialog.getByRole('button', { name: '打开为待确认草稿', exact: true }).tap()
  await expect(dialog).not.toBeVisible()
  await expect(editor).toContainText('手机未保存的最后正文')
  await page.unroute('**/api/v1/files/content?**')
  await page.getByRole('button', { name: '保存当前文件', exact: true }).tap()
  await expect(page.locator('.save-status')).toHaveText('已保存')
})
