import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
async function login(page: Page) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  page.on('dialog', (dialog) => void dialog.accept())
  await page.goto('/')
  await page.getByLabel('密码', { exact: true }).fill('folio-browser-test-password-2026')
  await page.getByRole('button', { name: '进入工作区' }).tap()
  await expect(page.getByRole('button', { name: '展开文件列表', exact: true })).toBeVisible()
}
async function drawer(page: Page) {
  await page.getByRole('button', { name: '展开文件列表', exact: true }).tap()
  const panel = page.getByRole('dialog', { name: '文件列表', exact: true })
  await expect(panel).toBeVisible()
  return panel
}
async function create(page: Page, kind: '笔记' | '文件夹', name: string) {
  const panel = page.getByRole('dialog', { name: '文件列表', exact: true })
  await panel.getByRole('button', { name: `新建${kind}`, exact: true }).tap()
  const dialog = page.getByRole('dialog', { name: kind === '笔记' ? '新建笔记' : '新建文件夹', exact: true })
  await dialog.getByLabel('名称', { exact: true }).fill(name)
  await dialog.getByRole('button', { name: '创建', exact: true }).tap()
  await expect(dialog).not.toBeVisible()
}

