import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const adminPassword = 'folio-browser-test-password-2026'
const userPassword = 'folio-user-password-2026'
async function login(page: Page, username = 'admin', password = adminPassword) {
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '进入工作区' }).click()
  await expect(page.getByRole('button', { name: '退出登录' })).toBeVisible()
}

test('用户管理创建、编辑、改密、禁用，明暗与移动页面', async ({ page, browser }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await login(page)
  await page.getByRole('link', { name: '用户设置', exact: true }).click()
  await page.getByRole('link', { name: '系统设置', exact: true }).click()
  await expect(page).toHaveURL(/\/system-setting$/)
  const username = `user-${Date.now()}`
  await page.getByRole('button', { name: '创建用户' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('用户名', { exact: true }).fill(username)
  await dialog.getByLabel('初始密码').fill(userPassword)
  await dialog.getByLabel('工作区配额').fill('2')
  await dialog.getByRole('button', { name: '创建', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByLabel('搜索用户名').fill(username)
  let row = page.getByRole('row').filter({ hasText: username })
  await expect(row).toContainText('0 B / 2 GB')
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('工作区配额').fill('16')
  await dialog.getByLabel('配额单位').selectOption(String(1024 ** 2))
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(row).toContainText('0 B / 16 MB')
  await expect(page.getByText('文件为本 · 自由书写')).toHaveCount(0)
  for (const theme of ['light', 'dark']) {
    await page.evaluate((theme) => document.documentElement.dataset.theme = theme, theme)
    await page.screenshot({ path: `test-results/users-${theme}-1440.png`, fullPage: true, animations: 'disabled' })
    const results = await new AxeBuilder({ page }).analyze()
    expect(results.violations).toEqual([])
  }
  await page.setViewportSize({ width: 1024, height: 768 })
  await page.screenshot({ path: 'test-results/users-dark-1024.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/users-dark-390.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const context = await browser.newContext()
  const user = await context.newPage()
  await login(user, username, userPassword)
  await expect(user.getByRole('link', { name: '系统设置' })).toHaveCount(0)
  await expect(user.getByLabel('工作区用量')).toHaveText('0 B / 16 MB')
  expect((await user.request.get('/api/v1/admin/users')).status()).toBe(403)
  await user.goto('/system-setting')
  await expect(user.getByRole('heading', { name: '无权访问系统设置' })).toBeVisible()
  await user.getByRole('link', { name: '返回工作区' }).click()
  await page.setViewportSize({ width: 1440, height: 900 })
  row = page.getByRole('row').filter({ hasText: username })
  await row.getByRole('button', { name: '重置密码', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('新密码', { exact: true }).fill('reset-password-2026')
  await dialog.getByRole('button', { name: '重置密码', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect((await user.request.get('/api/v1/auth/me')).status()).toBe(401)
  await login(user, username, 'reset-password-2026')
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('状态', { exact: true }).selectOption('disabled')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(row).toContainText('禁用')
  expect((await user.request.get('/api/v1/auth/me')).status()).toBe(401)
  await context.close()
})

test('进入系统设置并返回保留正文编辑器和标签', async ({ page }) => {
  await login(page)
  const me = await (await page.request.get('/api/v1/auth/me')).json()
  const name = `settings-session-${Date.now()}.json`
  await page.request.post('/api/v1/files', { headers: { 'X-CSRF-Token': me.csrfToken }, data: { path: name, content: '{"保留":true}' } })
  await page.getByRole('button', { name: '刷新文件列表' }).click()
  await page.getByRole('button', { name, exact: true }).click()
  const editor = page.getByRole('textbox', { name: '源码编辑器' })
  await expect(editor).toContainText('保留')
  await editor.evaluate((element) => element.setAttribute('data-session-probe', 'original'))
  await page.getByRole('link', { name: '用户设置', exact: true }).click()
  await page.getByRole('link', { name: '系统设置', exact: true }).click()
  await page.getByRole('link', { name: '返回工作区' }).click()
  await expect(editor).toHaveAttribute('data-session-probe', 'original')
  await expect(page.getByRole('tab', { name })).toBeVisible()
})

test('配额不足保留编辑正文，扩容后可重试；自助改密后重新登录保留会话', async ({ page, browser }) => {
  await login(page)
  const admin = await (await page.request.get('/api/v1/auth/me')).json()
  const headers = { 'X-CSRF-Token': admin.csrfToken }
  const username = `quota-${Date.now()}`
  const account = await (await page.request.post('/api/v1/admin/users', { headers, data: { username, password: userPassword, enabled: true, quota: 3 } })).json()
  const context = await browser.newContext()
  const user = await context.newPage()
  await login(user, username, userPassword)
  const me = await (await user.request.get('/api/v1/auth/me')).json()
  expect((await user.request.post('/api/v1/files', { headers: { 'X-CSRF-Token': me.csrfToken }, data: { path: 'quota.json', content: '{}' } })).status()).toBe(201)
  await user.getByRole('button', { name: '刷新文件列表' }).click()
  await user.getByRole('button', { name: 'quota.json', exact: true }).click()
  const editor = user.getByRole('textbox', { name: '源码编辑器' })
  const content = '{"保留超额正文":true}'
  await editor.fill(content)
  await expect(user.locator('.save-status')).toContainText('保存失败')
  await expect(editor).toContainText(content)
  const disk = await (await user.request.get('/api/v1/files/content?path=quota.json')).json()
  expect(disk.content).toBe('{}')
  await page.request.patch(`/api/v1/admin/users/${account.id}`, { headers, data: { username, enabled: true, quota: 1024, password: '' } })
  await user.getByRole('button', { name: '保存当前文件', exact: true }).click()
  await expect(user.locator('.save-status')).toHaveText('已保存')
  await user.getByRole('link', { name: '用户设置', exact: true }).click()
  const dialog = user.getByRole('region', { name: '账号', exact: true })
  await dialog.getByLabel('原密码', { exact: true }).fill(userPassword)
  await dialog.getByLabel('新密码', { exact: true }).fill('安全口令二六')
  await dialog.getByLabel('确认新密码', { exact: true }).fill('安全口令二六')
  await dialog.getByRole('button', { name: '修改密码', exact: true }).click()
  await expect(user.getByRole('status')).toContainText('密码已修改')
  await user.getByLabel('账号', { exact: true }).fill(username)
  await user.getByLabel('密码', { exact: true }).fill('安全口令二六')
  await user.getByRole('button', { name: '进入工作区' }).click()
  await user.getByRole('link', { name: '返回工作区', exact: true }).click()
  await expect(editor).toContainText(content)
  await expect(user.getByRole('tab', { name: 'quota.json' })).toBeVisible()
  await context.close()
})
